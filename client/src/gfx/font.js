export const FONT_CHARS = Array.from({ length: 64 }, (_, i) => String.fromCharCode(32 + i)).join('');
export const CHAR_W = 6;
export const CHAR_H = 9;

export function buildFont(scene) {
  const canvas = document.createElement('canvas');
  canvas.width = FONT_CHARS.length * CHAR_W;
  canvas.height = CHAR_H;
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = '#ffffff';
  [...FONT_CHARS].forEach((ch, i) => {
    const g = G[ch];
    if (!g) return;
    g.split(',').forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '1') ctx.fillRect(i * CHAR_W + x, y, 1, 1);
    });
  });
  scene.textures.addCanvas('font_px', canvas);
  const data = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: 'font_px',
    width: CHAR_W,
    height: CHAR_H,
    chars: FONT_CHARS,
    charsPerRow: FONT_CHARS.length,
    spacing: { x: 0, y: 0 },
    offset: { x: 0, y: 0 },
    lineSpacing: 1,
  });
  scene.cache.bitmapFont.add('px', data);
}
